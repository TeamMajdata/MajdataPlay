#nullable enable
using System;
using System.Collections;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading;
using Cysharp.Threading.Tasks;
using MajdataPlay.IO.Storage;
using NUnit.Framework;
using UnityEngine.TestTools;

namespace MajdataPlay.Tests.Plugins.IO.Storage
{
    /// <summary>Covers the asynchronous whole-file operations of file handles, including cancellation.</summary>
    public class StorageFileAsyncTests
    {
        /// <summary>The temporary directory of the current test.</summary>
        private TemporaryDirectory _temp = null!;

        /// <summary>Creates an empty temporary directory.</summary>
        [SetUp]
        public void SetUp()
        {
            _temp = new TemporaryDirectory();
        }

        /// <summary>Deletes the temporary directory.</summary>
        [TearDown]
        public void TearDown()
        {
            _temp.Dispose();
        }

        /// <summary>Creates deterministic bytes spanning several transfer buffers.</summary>
        /// <param name="length">The number of bytes.</param>
        /// <returns>The generated bytes.</returns>
        private static byte[] CreateBytes(int length)
        {
            return Enumerable.Range(0, length).Select(x => (byte)(x * 31)).ToArray();
        }

        /// <summary>Checks that bytes larger than one buffer round-trip through the asynchronous helpers.</summary>
        /// <returns>The test coroutine.</returns>
        [UnityTest]
        public IEnumerator WriteAllBytesAsync_RoundTripsLargeContent() => UniTask.ToCoroutine(async () =>
        {
            var file = _temp.Directory.CreateFile("large.bin");
            var bytes = CreateBytes(200_000);

            await file.WriteAllBytesAsync(bytes);
            var read = await file.ReadAllBytesAsync();

            Assert.That(read, Is.EqualTo(bytes));
        });

        /// <summary>Checks that text longer than one character buffer round-trips, including non-ASCII characters.</summary>
        /// <returns>The test coroutine.</returns>
        [UnityTest]
        public IEnumerator WriteAllTextAsync_RoundTripsLongText() => UniTask.ToCoroutine(async () =>
        {
            var file = _temp.Directory.CreateFile("long.txt");
            var text = string.Concat(Enumerable.Repeat("譜面 chart ", 2_000));

            await file.WriteAllTextAsync(text);
            var read = await file.ReadAllTextAsync();

            Assert.That(read, Is.EqualTo(text));
            Assert.That(file.ReadAllBytes()[0], Is.EqualTo(Encoding.UTF8.GetBytes("譜")[0]));
        });

        /// <summary>Checks that an explicit encoding is used for asynchronous writes and detected when reading.</summary>
        /// <returns>The test coroutine.</returns>
        [UnityTest]
        public IEnumerator WriteAllTextAsync_UsesExplicitEncoding() => UniTask.ToCoroutine(async () =>
        {
            var file = _temp.Directory.CreateFile("utf16.txt");

            await file.WriteAllTextAsync("héllo", Encoding.Unicode);
            var read = await file.ReadAllTextAsync(Encoding.ASCII);

            Assert.That(read, Is.EqualTo("héllo"));
        });

        /// <summary>Checks that asynchronous writes truncate longer previous content.</summary>
        /// <returns>The test coroutine.</returns>
        [UnityTest]
        public IEnumerator WriteAllBytesAsync_TruncatesPreviousContent() => UniTask.ToCoroutine(async () =>
        {
            var file = _temp.WriteText("a.txt", "a long original");

            await file.WriteAllBytesAsync(new byte[] { 0x61 });

            Assert.That(file.ReadAllText(), Is.EqualTo("a"));
        });

        /// <summary>Checks that null content is rejected synchronously, before any task is started.</summary>
        [Test]
        public void WriteAllAsync_RejectsNullContentSynchronously()
        {
            var file = _temp.Directory.CreateFile("a.txt");

            Assert.Throws<ArgumentNullException>(() => file.WriteAllBytesAsync(null!));
            Assert.Throws<ArgumentNullException>(() => file.WriteAllTextAsync(null!));
        }

        /// <summary>Checks that a pre-cancelled token cancels every asynchronous operation and leaves the file untouched.</summary>
        /// <returns>The test coroutine.</returns>
        [UnityTest]
        public IEnumerator AsyncOperations_HonourPreCancelledToken() => UniTask.ToCoroutine(async () =>
        {
            var file = _temp.WriteText("a.txt", "keep");
            using var cancellation = new CancellationTokenSource();
            cancellation.Cancel();
            var token = cancellation.Token;

            await AsyncAssert.ThrowsAsync<OperationCanceledException>(() => file.ReadAllBytesAsync(token));
            await AsyncAssert.ThrowsAsync<OperationCanceledException>(() => file.ReadAllTextAsync(cancellationToken: token));
            await AsyncAssert.ThrowsAsync<OperationCanceledException>(() => file.WriteAllBytesAsync(new byte[1], token));
            await AsyncAssert.ThrowsAsync<OperationCanceledException>(() => file.WriteAllTextAsync("x", cancellationToken: token));
            await AsyncAssert.ThrowsAsync<OperationCanceledException>(() => file.CopyToAsync(_temp.Directory, "copy.txt", cancellationToken: token));

            Assert.That(file.ReadAllText(), Is.EqualTo("keep"));
            Assert.That(_temp.Directory.FindFile("copy.txt"), Is.Null);
        });

        /// <summary>Checks that asynchronous reads and writes of a missing file report the missing file.</summary>
        /// <returns>The test coroutine.</returns>
        [UnityTest]
        public IEnumerator AsyncOperations_ReportMissingFile() => UniTask.ToCoroutine(async () =>
        {
            var missing = FileSystem.File.Open(Path.Combine(_temp.Location, "missing.txt"));

            await AsyncAssert.ThrowsAsync<FileNotFoundException>(() => missing.ReadAllBytesAsync());
            await AsyncAssert.ThrowsAsync<FileNotFoundException>(() => missing.ReadAllTextAsync());
            await AsyncAssert.ThrowsAsync<FileNotFoundException>(() => missing.WriteAllBytesAsync(new byte[1]));
            await AsyncAssert.ThrowsAsync<FileNotFoundException>(() => missing.WriteAllTextAsync("x"));
            await AsyncAssert.ThrowsAsync<FileNotFoundException>(() => missing.CopyToAsync(_temp.Directory, "copy.txt"));

            Assert.That(missing.Exists, Is.False);
        });

        /// <summary>Checks that an asynchronous copy creates a new destination with the source content.</summary>
        /// <returns>The test coroutine.</returns>
        [UnityTest]
        public IEnumerator CopyToAsync_CreatesDestination() => UniTask.ToCoroutine(async () =>
        {
            var source = _temp.WriteText("source.txt", "payload");
            var target = _temp.Directory.CreateDirectory("target");

            var copy = await source.CopyToAsync(target, "copy.txt");

            Assert.That(copy.Location, Is.EqualTo(Path.Combine(target.Location, "copy.txt")));
            Assert.That(copy.ReadAllText(), Is.EqualTo("payload"));
            Assert.That(source.ReadAllText(), Is.EqualTo("payload"));
        });

        /// <summary>Checks that an asynchronous copy refuses an occupied name unless overwriting is requested.</summary>
        /// <returns>The test coroutine.</returns>
        [UnityTest]
        public IEnumerator CopyToAsync_OverwritesOnlyOnRequest() => UniTask.ToCoroutine(async () =>
        {
            var source = _temp.WriteText("source.txt", "new");
            var target = _temp.Directory.CreateDirectory("target");
            var existing = target.CreateFile("copy.txt");
            existing.WriteAllText("old content");

            await AsyncAssert.ThrowsAsync<IOException>(() => source.CopyToAsync(target, "copy.txt"));
            var keptOld = existing.ReadAllText();
            await source.CopyToAsync(target, "copy.txt", overwrite: true);

            Assert.That(keptOld, Is.EqualTo("old content"));
            Assert.That(existing.ReadAllText(), Is.EqualTo("new"));
        });

        /// <summary>Checks that the asynchronous copy validates its destination and name before starting a task.</summary>
        [Test]
        public void CopyToAsync_ValidatesArgumentsSynchronously()
        {
            var source = _temp.WriteText("source.txt", "x");

            Assert.Throws<ArgumentNullException>(() => source.CopyToAsync(null!, "a"));
            Assert.Throws<ArgumentException>(() => source.CopyToAsync(_temp.Directory, "a/b"));
        }
    }
}
