#nullable enable
using AOT;
using MajdataPlay.Diagnostics;
using MajdataPlay.IO;
using ManagedBass;
using ManagedBass.Mix;
using ManagedBass.Wasapi;
using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.Threading;

namespace MajdataPlay.Tests.AudioRecorderLatencyValidation
{
    /// <summary>Checks on the real output device that <see cref="BassAudioRecorder.PlaybackDelay"/> places captured audio where it is played.</summary>
    /// <remarks>
    /// Each case plays short 18 kHz bursts at about -50 dBFS through the same Bass output topology as <c>AudioManager</c>, records them with
    /// the production recorder and latency probe, and compares the delayed onsets with an independent playback time.
    /// </remarks>
    internal static class Program
    {
        /// <summary>Sets the burst amplitude, about -50 dBFS, so the test stays inaudible.</summary>
        private const float ClickAmplitude = 0.003f;
        /// <summary>Sets the burst tone frequency in hertz.</summary>
        private const double ClickFrequency = 18000;
        /// <summary>Sets the burst duration in seconds.</summary>
        private const double ClickSeconds = 0.01;
        /// <summary>Sets the duration of each click stream, including its trailing silence, in seconds.</summary>
        private const double ClickStreamSeconds = 0.4;
        /// <summary>Sets the captured level that marks a burst onset; only this process's channels reach the capture DSP.</summary>
        private const float OnsetThreshold = ClickAmplitude * 0.1f;
        /// <summary>Sets the number of bursts per case.</summary>
        private const int ClickCount = 8;
        /// <summary>Sets the pause before each burst in milliseconds.</summary>
        private const int ClickIntervalMilliseconds = 700;
        /// <summary>Sets how long the reported playback position of a BassSimple burst is sampled, in milliseconds.</summary>
        private const int HeardSamplingMilliseconds = 250;
        /// <summary>Sets how long the output runs before recording starts, in milliseconds.</summary>
        private const int WarmUpMilliseconds = 500;
        /// <summary>Sets how long recording continues after the last burst, in milliseconds.</summary>
        private const int TailMilliseconds = 300;
        /// <summary>Sets the recorder's buffer length, as <c>AudioManager</c> does.</summary>
        private const int RecorderBufferSeconds = 4;
        /// <summary>Sets how much captured audio one case can store, covering every burst, the tail, and a margin.</summary>
        private const int CaptureCapacityMilliseconds = (ClickCount * (ClickIntervalMilliseconds + HeardSamplingMilliseconds)) + TailMilliseconds + 2000;
        /// <summary>Sets the BassSimple tolerance between a delayed onset and the playback start reported by BASS.</summary>
        private const double BassSimpleToleranceSeconds = 0.005;
        /// <summary>Sets how far a WASAPI onset may precede the measured output latency.</summary>
        private const double WasapiEarlyToleranceSeconds = 0.001;
        /// <summary>Sets how far a WASAPI onset may follow the measured output latency plus one output block.</summary>
        private const double WasapiLateToleranceSeconds = 0.002;
        /// <summary>Sets the largest WASAPI output latency accepted as plausible, in seconds.</summary>
        private const double MaximumPlausibleLatencySeconds = 0.2;
        /// <summary>Sets how long the stall cases block the output thread, like a blocking garbage collection in the Editor.</summary>
        private const int StallMilliseconds = 300;
        /// <summary>Sets the burst before which the stall cases block the output thread.</summary>
        private const int StallBeforeClick = 4;
        /// <summary>Roots the burst generator for native callbacks.</summary>
        private static readonly StreamProcedure s_clickProcedure = WriteClick;
        /// <summary>Roots the WASAPI output callback for native callbacks.</summary>
        private static readonly WasapiProcedure s_wasapiProcedure = PullMixer;
        /// <summary>Roots the BassSimple stall DSP for native callbacks.</summary>
        private static readonly DSPProcedure s_stallProcedure = StallOutputDsp;
        /// <summary>Stores a one-time output thread stall in milliseconds, consumed by the next output callback.</summary>
        private static int s_pendingStallMilliseconds;
        /// <summary>Counts the frames generated by each click stream, indexed by the stream's user value.</summary>
        private static readonly long[] s_clickFramesWritten = new long[ClickCount];
        /// <summary>Synchronizes the reference WASAPI latency between the output callback and the main thread.</summary>
        private static readonly object s_referenceGate = new object();
        /// <summary>Stores the sample rate of the click streams.</summary>
        private static int s_clickRate;
        /// <summary>Stores the global mixer pulled by the WASAPI output callback.</summary>
        private static int s_mixer;
        /// <summary>Measures WASAPI latency in the output callback with a probe separate from the recorder's.</summary>
        private static BassOutputLatencyProbe? s_referenceProbe;
        /// <summary>Indicates whether the output callback accumulates reference latencies.</summary>
        private static bool s_isMeasuringReference;
        /// <summary>Sums the reference latencies in seconds.</summary>
        private static double s_referenceLatencySum;
        /// <summary>Counts the reference latencies.</summary>
        private static int s_referenceLatencyCount;
        /// <summary>Stores the largest number of bytes requested by one WASAPI output callback.</summary>
        private static int s_largestCallbackBytes;
        /// <summary>Stores the byte rate of the 32-bit float data rendered for WASAPI.</summary>
        private static double s_renderBytesPerSecond;
        /// <summary>Stores the <see cref="Stopwatch"/> timestamp of the first measured WASAPI output callback.</summary>
        private static long s_firstCallbackTimestamp;
        /// <summary>Counts the bytes rendered by measured WASAPI output callbacks.</summary>
        private static long s_renderedBytes;
        /// <summary>Stores the smallest wall time minus rendered audio time of a measured callback, in seconds.</summary>
        private static double s_minimumRenderLag;
        /// <summary>Stores the largest wall time minus rendered audio time of a measured callback, in seconds.</summary>
        private static double s_maximumRenderLag;
        /// <summary>Counts completed assertions.</summary>
        private static int s_assertions;

        /// <summary>Runs each output configuration and reports a pass or failure marker.</summary>
        /// <param name="args">Pass <c>--exclusive</c> to add the exclusive, asynchronous, raw WASAPI case, which briefly takes the device.</param>
        /// <returns>Zero if every case passes, or one after a failure.</returns>
        private static int Main(string[] args)
        {
            var cases = new List<(string Name, Action Run)>
            {
                ("BassSimple device buffer 32 ms, period 8 ms", () => RunBassSimple(32, 8, 0)),
                ("BassSimple device buffer 64 ms, period 16 ms", () => RunBassSimple(64, 16, 0)),
                ($"BassSimple device buffer 32 ms with a {StallMilliseconds} ms output stall", () => RunBassSimple(32, 8, StallMilliseconds)),
                ("WASAPI shared", () => RunWasapi(false, 0)),
                ($"WASAPI shared with a {StallMilliseconds} ms output stall", () => RunWasapi(false, StallMilliseconds))
            };
            if (Array.IndexOf(args, "--exclusive") >= 0)
            {
                cases.Add(("WASAPI exclusive + async + raw", () => RunWasapi(true, 0)));
            }
            var failed = 0;
            foreach (var testCase in cases)
            {
                Console.WriteLine($"== {testCase.Name}");
                try
                {
                    testCase.Run();
                    Console.WriteLine($"PASS {testCase.Name}");
                }
                catch (Exception exception)
                {
                    failed++;
                    Console.Error.WriteLine($"FAIL {testCase.Name}: {exception}");
                }
            }
            var marker = failed == 0 ? "AUDIO_RECORDER_LATENCY_VALIDATION_PASSED" : "AUDIO_RECORDER_LATENCY_VALIDATION_FAILED";
            Console.WriteLine($"{marker} ({cases.Count - failed} passed, {failed} failed, {s_assertions} assertions)");
            return failed == 0 ? 0 : 1;
        }

        /// <summary>Checks the BassSimple device stream against the playback start that BASS reports for each burst.</summary>
        /// <param name="deviceBufferMilliseconds">The device buffer length passed to BASS.</param>
        /// <param name="devicePeriodMilliseconds">The device update period passed to BASS.</param>
        /// <param name="stallMilliseconds">How long a DSP running before the recorder blocks the output thread once, or zero for no stall.</param>
        private static void RunBassSimple(int deviceBufferMilliseconds, int devicePeriodMilliseconds, int stallMilliseconds)
        {
            // The game's AudioManager configuration, with the clamped update period.
            Bass.Configure(Configuration.UpdatePeriod, 100);
            Bass.Configure(Configuration.PlaybackBufferLength, 1000);
            Bass.Configure(Configuration.DevicePeriod, devicePeriodMilliseconds);
            Bass.Configure(Configuration.DeviceBufferLength, deviceBufferMilliseconds);
            Bass.Configure(Configuration.DevNonStop, true);
            Check(Bass.Init(), "Bass.Init succeeds: " + Bass.LastError);
            try
            {
                var device = Bass.CreateStream(0, 0, BassFlags.Default, StreamProcedureType.Device);
                Check(device != 0, "the device output stream is created: " + Bass.LastError);
                if (Bass.ChannelIsActive(device) != PlaybackState.Playing)
                {
                    Check(Bass.ChannelPlay(device), "the device output stream starts: " + Bass.LastError);
                }
                if (stallMilliseconds > 0)
                {
                    // A higher priority runs this DSP before the recorder's, on the same output thread.
                    Check(Bass.ChannelSetDSP(device, s_stallProcedure, IntPtr.Zero, 0) != 0, "the stall DSP is attached: " + Bass.LastError);
                }
                var errorsBefore = MajDebug.ErrorCount;
                using (var recorder = new BassAudioRecorder(device, RecorderBufferSeconds, BassOutputLatencyProbe.CreateForDeviceStream(device)))
                {
                    s_clickRate = recorder.SampleRate;
                    Thread.Sleep(WarmUpMilliseconds);
                    var capture = new CapturedAudio(recorder, CaptureCapacityMilliseconds);
                    var heardSeconds = new double[ClickCount];
                    var startTimestamp = Stopwatch.GetTimestamp();
                    recorder.Start();
                    for (var i = 0; i < ClickCount; i++)
                    {
                        WaitBeforeClick(i, stallMilliseconds);
                        var click = CreateClick(i, BassFlags.Float);
                        Check(Bass.ChannelPlay(click), "a burst stream starts: " + Bass.LastError);
                        heardSeconds[i] = MeasureHeardStart(click, startTimestamp);
                        capture.Drain(recorder);
                        Bass.StreamFree(click);
                    }
                    Thread.Sleep(TailMilliseconds);
                    recorder.Stop();
                    capture.Drain(recorder);

                    var playbackDelay = recorder.PlaybackDelay.TotalSeconds;
                    var onsets = FindOnsets(capture, recorder.Channels, recorder.SampleRate);
                    Console.WriteLine($"  PlaybackDelay {playbackDelay * 1000:F1} ms, {recorder.SampleRate} Hz");
                    var insertedSilence = CheckTimeline(recorder, stallMilliseconds);
                    Check(recorder.DroppedFrames == 0, "no captured frame is dropped");
                    Check(onsets.Count == ClickCount, $"every burst is captured once, found {onsets.Count}");
                    Check(playbackDelay > 0, "the playback delay includes a measured output latency");
                    Console.WriteLine("  click   onset ms   delayed ms   BASS heard ms   error ms   without gap fill ms");
                    for (var i = 0; i < ClickCount; i++)
                    {
                        var onsetSeconds = onsets[i] / (double)recorder.SampleRate;
                        var delayedSeconds = onsetSeconds + playbackDelay;
                        var error = delayedSeconds - heardSeconds[i];
                        var continuousError = error - SilenceBefore(i, stallMilliseconds, insertedSilence);
                        Console.WriteLine($"  {i,5} {onsetSeconds * 1000,10:F1} {delayedSeconds * 1000,12:F1} {heardSeconds[i] * 1000,15:F1} "
                            + $"{error * 1000,10:F1} {continuousError * 1000,21:F1}");
                        Check(Math.Abs(error) <= BassSimpleToleranceSeconds, $"burst {i} is delayed to its reported playback start, error {error * 1000:F1} ms");
                        CheckContinuousAssumptionFails(i, stallMilliseconds, continuousError);
                    }
                }
                Check(MajDebug.ErrorCount == errorsBefore, "the recorder logs no error");
            }
            finally
            {
                Bass.Free();
            }
        }

        /// <summary>Checks the WASAPI global mixer against the latency buffered by BASSWASAPI and the time each burst was added.</summary>
        /// <param name="exclusive">Whether to request exclusive, asynchronous, raw output with the game's fallback order.</param>
        /// <param name="stallMilliseconds">How long the output callback blocks once, or zero for no stall.</param>
        private static void RunWasapi(bool exclusive, int stallMilliseconds)
        {
            Check(Bass.Init(Bass.NoSoundDevice), "Bass.Init on the no-sound device succeeds: " + Bass.LastError);
            try
            {
                InitializeWasapi(exclusive);
                try
                {
                    Check(BassWasapi.GetInfo(out var info), "the WASAPI output format is readable: " + Bass.LastError);
                    s_clickRate = info.Frequency;
                    s_mixer = BassMix.CreateMixerStream(info.Frequency, info.Channels, BassFlags.MixerNonStop | BassFlags.Decode | BassFlags.Float);
                    Check(s_mixer != 0, "the global mixer is created: " + Bass.LastError);
                    Bass.ChannelSetAttribute(s_mixer, ChannelAttribute.Buffer, 0);
                    s_referenceProbe = BassOutputLatencyProbe.CreateForWasapi();
                    var errorsBefore = MajDebug.ErrorCount;
                    using (var recorder = new BassAudioRecorder(s_mixer, RecorderBufferSeconds, BassOutputLatencyProbe.CreateForWasapi()))
                    {
                        Check(BassWasapi.Start(), "the WASAPI output starts: " + Bass.LastError);
                        Thread.Sleep(WarmUpMilliseconds);
                        var capture = new CapturedAudio(recorder, CaptureCapacityMilliseconds);
                        var playSeconds = new double[ClickCount];
                        lock (s_referenceGate)
                        {
                            s_referenceLatencySum = 0;
                            s_referenceLatencyCount = 0;
                            s_largestCallbackBytes = 0;
                            s_renderBytesPerSecond = (double)info.Frequency * info.Channels * sizeof(float);
                            s_firstCallbackTimestamp = 0;
                            s_renderedBytes = 0;
                            s_minimumRenderLag = double.MaxValue;
                            s_maximumRenderLag = double.MinValue;
                            s_isMeasuringReference = true;
                        }
                        var startTimestamp = Stopwatch.GetTimestamp();
                        recorder.Start();
                        for (var i = 0; i < ClickCount; i++)
                        {
                            WaitBeforeClick(i, stallMilliseconds);
                            var click = CreateClick(i, BassFlags.Float | BassFlags.Decode);
                            var playTimestamp = Stopwatch.GetTimestamp();
                            Check(BassMix.MixerAddChannel(s_mixer, click, BassFlags.MixerChanNoRampin | BassFlags.AutoFree), "a burst joins the mixer: " + Bass.LastError);
                            playSeconds[i] = Seconds(playTimestamp - startTimestamp);
                            capture.Drain(recorder);
                        }
                        Thread.Sleep(TailMilliseconds);
                        recorder.Stop();
                        double referenceLatency;
                        double blockSeconds;
                        int referenceCount;
                        double renderJitter;
                        lock (s_referenceGate)
                        {
                            s_isMeasuringReference = false;
                            referenceCount = s_referenceLatencyCount;
                            referenceLatency = referenceCount == 0 ? 0 : s_referenceLatencySum / referenceCount;
                            blockSeconds = s_largestCallbackBytes / s_renderBytesPerSecond;
                            renderJitter = s_maximumRenderLag - s_minimumRenderLag;
                        }
                        capture.Drain(recorder);

                        var playbackDelay = recorder.PlaybackDelay.TotalSeconds;
                        var onsets = FindOnsets(capture, recorder.Channels, recorder.SampleRate);
                        Console.WriteLine($"  PlaybackDelay {playbackDelay * 1000:F1} ms, reference output latency {referenceLatency * 1000:F1} ms "
                            + $"from {referenceCount} callbacks, output block {blockSeconds * 1000:F1} ms, {info.Frequency} Hz x{info.Channels}");
                        // A callback that runs late renders audio whose position belongs to an earlier wall time; this spread bounds that error.
                        Console.WriteLine($"  Render pacing: callback wall time minus rendered audio time spans {renderJitter * 1000:F1} ms");
                        Check(referenceCount > 0, "the output callback measured the buffered latency");
                        Check(referenceLatency > 0 && referenceLatency < MaximumPlausibleLatencySeconds, "the output latency is plausible");
                        Check(playbackDelay >= referenceLatency - WasapiEarlyToleranceSeconds, "the playback delay includes the output latency");
                        var insertedSilence = CheckTimeline(recorder, stallMilliseconds);
                        Check(recorder.DroppedFrames == 0, "no captured frame is dropped");
                        Check(onsets.Count == ClickCount, $"every burst is captured once, found {onsets.Count}");
                        Console.WriteLine("  click    play ms   delayed ms   delayed - play ms   without gap fill ms");
                        for (var i = 0; i < ClickCount; i++)
                        {
                            var delayedSeconds = onsets[i] / (double)recorder.SampleRate + playbackDelay;
                            var lag = delayedSeconds - playSeconds[i];
                            var continuousLag = lag - SilenceBefore(i, stallMilliseconds, insertedSilence);
                            Console.WriteLine($"  {i,5} {playSeconds[i] * 1000,10:F1} {delayedSeconds * 1000,12:F1} {lag * 1000,19:F1} {continuousLag * 1000,21:F1}");
                            Check(lag >= referenceLatency - WasapiEarlyToleranceSeconds && lag <= referenceLatency + blockSeconds + WasapiLateToleranceSeconds,
                                $"burst {i} is delayed by the output latency within one output block, got {lag * 1000:F1} ms");
                            CheckContinuousAssumptionFails(i, stallMilliseconds, continuousLag - referenceLatency);
                        }
                    }
                    Check(MajDebug.ErrorCount == errorsBefore, "the recorder logs no error");
                }
                finally
                {
                    BassWasapi.Free();
                    s_referenceProbe?.Dispose();
                    s_referenceProbe = null;
                    if (s_mixer != 0)
                    {
                        Bass.StreamFree(s_mixer);
                        s_mixer = 0;
                    }
                }
            }
            finally
            {
                Bass.Free();
            }
        }

        /// <summary>Initializes the default WASAPI output like <c>AudioManager</c>, falling back in the game's order.</summary>
        /// <param name="exclusive">Whether to start from exclusive raw output; otherwise only plain shared output is tried.</param>
        /// <exception cref="InvalidOperationException">No combination can be initialized.</exception>
        private static void InitializeWasapi(bool exclusive)
        {
            var combinations = exclusive
                ? new[] { (Exclusive: true, Raw: true), (Exclusive: true, Raw: false), (Exclusive: false, Raw: true), (Exclusive: false, Raw: false) }
                : new[] { (Exclusive: false, Raw: false) };
            foreach (var combination in combinations)
            {
                var flags = WasapiInitFlags.EventDriven;
                if (combination.Exclusive)
                {
                    flags |= WasapiInitFlags.Exclusive | WasapiInitFlags.Async;
                }
                else
                {
                    flags |= WasapiInitFlags.Shared;
                }
                if (combination.Raw)
                {
                    flags |= WasapiInitFlags.Raw;
                }
                var buffer = combination.Exclusive ? 0.02f : 0f;
                var period = combination.Exclusive ? 0.005f : 0f;
                if (BassWasapi.Init(-1, 0, 0, flags, buffer, period, s_wasapiProcedure))
                {
                    Console.WriteLine($"  WASAPI initialized: exclusive={combination.Exclusive}, raw={combination.Raw}, flags={flags}");
                    return;
                }
                Console.WriteLine($"  WASAPI init failed for exclusive={combination.Exclusive}, raw={combination.Raw}: {Bass.LastError}");
                BassWasapi.Free();
            }
            throw new InvalidOperationException("No WASAPI output combination could be initialized.");
        }

        /// <summary>Prints and checks how the recorder repaired its playback timeline.</summary>
        /// <param name="recorder">The stopped recorder.</param>
        /// <param name="stallMilliseconds">The injected stall, or zero when the output ran without one.</param>
        /// <returns>The silence inserted for output gaps, in seconds.</returns>
        private static double CheckTimeline(BassAudioRecorder recorder, int stallMilliseconds)
        {
            var gaps = recorder.OutputGapCount;
            var insertedSilence = recorder.InsertedSilence.TotalSeconds;
            Console.WriteLine($"  Timeline: {gaps} output gaps, {insertedSilence * 1000:F1} ms of silence inserted, "
                + $"largest uncorrected deviation {recorder.LargestTimelineDeviation.TotalMilliseconds:F1} ms");
            if (stallMilliseconds <= 0)
            {
                Check(gaps == 0, "an output without stalls never gets silence inserted");
                return insertedSilence;
            }
            Check(gaps == 1, $"the single stall is filled once, got {gaps} gaps");
            // The device keeps playing what it had buffered when the stall began, so the audible gap is somewhat shorter than the stall.
            Check(insertedSilence >= stallMilliseconds / 2000.0 && insertedSilence <= (stallMilliseconds + 50) / 1000.0,
                $"the inserted silence matches the audible gap of the stall, got {insertedSilence * 1000:F1} ms");
            return insertedSilence;
        }

        /// <summary>Gets the silence inserted before a burst, which is the whole gap for bursts after the stall and zero otherwise.</summary>
        /// <param name="index">The burst index.</param>
        /// <param name="stallMilliseconds">The injected stall, or zero.</param>
        /// <param name="insertedSilence">The silence the recorder inserted, in seconds.</param>
        /// <returns>The silence that precedes the burst on the recorded timeline, in seconds.</returns>
        private static double SilenceBefore(int index, int stallMilliseconds, double insertedSilence)
        {
            return stallMilliseconds > 0 && index >= StallBeforeClick ? insertedSilence : 0;
        }

        /// <summary>Checks that assuming continuous capture would have placed a burst after the stall early by about the gap.</summary>
        /// <param name="index">The burst index.</param>
        /// <param name="stallMilliseconds">The injected stall, or zero.</param>
        /// <param name="continuousError">The burst's error relative to its reference if no silence had been inserted, in seconds.</param>
        private static void CheckContinuousAssumptionFails(int index, int stallMilliseconds, double continuousError)
        {
            if (stallMilliseconds > 0 && index >= StallBeforeClick)
            {
                Check(continuousError <= -stallMilliseconds / 2000.0,
                    $"without the gap fill burst {index} would land early by about the stall, got {continuousError * 1000:F1} ms");
            }
        }

        /// <summary>Waits until the next burst, requesting the one-time output stall early in the wait before <see cref="StallBeforeClick"/>.</summary>
        /// <param name="index">The index of the burst about to be played.</param>
        /// <param name="stallMilliseconds">The stall length, or zero for no stall.</param>
        /// <remarks>The stall ends well before the burst, so the burst itself is played on time after the output has recovered.</remarks>
        private static void WaitBeforeClick(int index, int stallMilliseconds)
        {
            if (stallMilliseconds <= 0 || index != StallBeforeClick)
            {
                Thread.Sleep(ClickIntervalMilliseconds);
                return;
            }
            var beforeStall = ClickIntervalMilliseconds / 4;
            Thread.Sleep(beforeStall);
            Interlocked.Exchange(ref s_pendingStallMilliseconds, stallMilliseconds);
            Thread.Sleep(ClickIntervalMilliseconds - beforeStall);
        }

        /// <summary>Blocks the calling output thread once when a stall has been requested.</summary>
        private static void ConsumePendingStall()
        {
            var milliseconds = Interlocked.Exchange(ref s_pendingStallMilliseconds, 0);
            if (milliseconds > 0)
            {
                Thread.Sleep(milliseconds);
            }
        }

        /// <summary>Stalls the BassSimple output thread before the recorder's DSP, as a paused output thread would.</summary>
        /// <param name="handle">The DSP handle.</param>
        /// <param name="channel">The device output stream.</param>
        /// <param name="buffer">The sample block, left unchanged.</param>
        /// <param name="length">The block length in bytes.</param>
        /// <param name="user">The unused user pointer.</param>
        [MonoPInvokeCallback(typeof(DSPProcedure))]
        private static void StallOutputDsp(int handle, int channel, IntPtr buffer, int length, IntPtr user)
        {
            ConsumePendingStall();
        }

        /// <summary>Creates a stereo float stream that plays one burst followed by silence.</summary>
        /// <param name="index">The burst index, which selects the stream's generator state.</param>
        /// <param name="flags">The stream flags, such as <see cref="BassFlags.Decode"/> for mixer sources.</param>
        /// <returns>The stream handle.</returns>
        private static int CreateClick(int index, BassFlags flags)
        {
            s_clickFramesWritten[index] = 0;
            var stream = Bass.CreateStream(s_clickRate, 2, flags, s_clickProcedure, new IntPtr(index));
            Check(stream != 0, "a burst stream is created: " + Bass.LastError);
            // Without the start ramp the burst's first frame is at full burst level, so its onset is exact.
            Bass.ChannelSetAttribute(stream, ChannelAttribute.NoRamp, 1);
            return stream;
        }

        /// <summary>Estimates when BASS reports a burst stream as starting to play, from its playback position.</summary>
        /// <param name="stream">The playing burst stream.</param>
        /// <param name="startTimestamp">The <see cref="Stopwatch"/> timestamp taken just before the recorder started.</param>
        /// <returns>The median estimated playback start in seconds after the recorder started.</returns>
        private static double MeasureHeardStart(int stream, long startTimestamp)
        {
            // Preallocated so that sampling never starts a collection that would pause the managed capture DSP.
            var estimates = new double[HeardSamplingMilliseconds * 2];
            var count = 0;
            var until = Stopwatch.GetTimestamp() + Stopwatch.Frequency * HeardSamplingMilliseconds / 1000;
            while (Stopwatch.GetTimestamp() < until && count < estimates.Length)
            {
                var position = Bass.ChannelGetPosition(stream);
                var now = Stopwatch.GetTimestamp();
                if (position > 0)
                {
                    estimates[count] = Seconds(now - startTimestamp) - Bass.ChannelBytes2Seconds(stream, position);
                    count++;
                }
                Thread.Sleep(1);
            }
            Check(count > 0, "BASS reports the burst's playback position");
            Array.Sort(estimates, 0, count);
            return estimates[count / 2];
        }

        /// <summary>Finds the first frame of each burst in the captured left channel.</summary>
        /// <param name="capture">The captured audio.</param>
        /// <param name="channels">The number of interleaved channels.</param>
        /// <param name="sampleRate">The capture sample rate.</param>
        /// <returns>The frame index of each onset, in capture order.</returns>
        private static List<long> FindOnsets(CapturedAudio capture, int channels, int sampleRate)
        {
            var onsets = new List<long>();
            var ignoreUntil = 0L;
            var frames = capture.Count / channels;
            for (var frame = 0L; frame < frames; frame++)
            {
                if (frame >= ignoreUntil && Math.Abs(capture.Samples[(int)(frame * channels)]) > OnsetThreshold)
                {
                    onsets.Add(frame);
                    ignoreUntil = frame + sampleRate / 5;
                }
            }
            return onsets;
        }

        /// <summary>Converts <see cref="Stopwatch"/> ticks to seconds.</summary>
        /// <param name="ticks">The tick count.</param>
        /// <returns>The duration in seconds.</returns>
        private static double Seconds(long ticks)
        {
            return ticks / (double)Stopwatch.Frequency;
        }

        /// <summary>Throws when a validation condition fails.</summary>
        /// <param name="condition">The observed condition.</param>
        /// <param name="message">The failure description.</param>
        /// <exception cref="Exception">The condition is false.</exception>
        private static void Check(bool condition, string message)
        {
            s_assertions++;
            if (!condition)
            {
                throw new Exception(message);
            }
        }

        /// <summary>Generates a burst stream block: an 18 kHz cosine burst at about -50 dBFS, then silence until the stream ends.</summary>
        /// <param name="handle">The burst stream.</param>
        /// <param name="buffer">The stereo float buffer to fill.</param>
        /// <param name="length">The buffer length in bytes.</param>
        /// <param name="user">The burst index.</param>
        /// <returns>The number of bytes written, combined with the end flag once the stream is complete.</returns>
        [MonoPInvokeCallback(typeof(StreamProcedure))]
        private static unsafe int WriteClick(int handle, IntPtr buffer, int length, IntPtr user)
        {
            var index = (int)user;
            var samples = new Span<float>((void*)buffer, length / sizeof(float));
            var firstFrame = s_clickFramesWritten[index];
            var burstFrames = (long)(s_clickRate * ClickSeconds);
            var totalFrames = (long)(s_clickRate * ClickStreamSeconds);
            var frames = samples.Length / 2;
            for (var i = 0; i < frames; i++)
            {
                var frame = firstFrame + i;
                var value = frame < burstFrames ? ClickAmplitude * (float)Math.Cos(2 * Math.PI * ClickFrequency * frame / s_clickRate) : 0f;
                samples[i * 2] = value;
                samples[(i * 2) + 1] = value;
            }
            s_clickFramesWritten[index] = firstFrame + frames;
            return firstFrame + frames >= totalFrames ? length | (int)StreamProcedureType.End : length;
        }

        /// <summary>Feeds the WASAPI output from the global mixer and measures the reference latency, like <c>AudioManager</c>'s callback.</summary>
        /// <param name="buffer">The float buffer requested by BASSWASAPI.</param>
        /// <param name="length">The requested length in bytes.</param>
        /// <param name="user">The unused user pointer.</param>
        /// <returns>The number of bytes rendered by the mixer.</returns>
        [MonoPInvokeCallback(typeof(WasapiProcedure))]
        private static int PullMixer(IntPtr buffer, int length, IntPtr user)
        {
            ConsumePendingStall();
            lock (s_referenceGate)
            {
                if (s_isMeasuringReference && s_referenceProbe != null)
                {
                    var latency = s_referenceProbe.Measure(0);
                    if (latency >= 0)
                    {
                        s_referenceLatencySum += latency;
                        s_referenceLatencyCount++;
                    }
                    s_largestCallbackBytes = Math.Max(s_largestCallbackBytes, length);
                    var now = Stopwatch.GetTimestamp();
                    if (s_firstCallbackTimestamp == 0)
                    {
                        s_firstCallbackTimestamp = now;
                    }
                    var renderLag = Seconds(now - s_firstCallbackTimestamp) - (s_renderedBytes / s_renderBytesPerSecond);
                    s_minimumRenderLag = Math.Min(s_minimumRenderLag, renderLag);
                    s_maximumRenderLag = Math.Max(s_maximumRenderLag, renderLag);
                    s_renderedBytes += length;
                }
            }
            return Bass.ChannelGetData(s_mixer, buffer, length);
        }

        /// <summary>Collects recorder output in storage allocated before recording starts.</summary>
        /// <remarks>
        /// The capture DSP and the WASAPI callback are managed code, so a garbage collection while draining would pause them and
        /// shift the captured timeline; allocating everything up front keeps the measurement free of such pauses.
        /// </remarks>
        private sealed class CapturedAudio
        {
            /// <summary>Stores the reusable transfer buffer for one read.</summary>
            private readonly float[] _transfer;

            /// <summary>Allocates storage for a case.</summary>
            /// <param name="recorder">The recorder whose format sizes the storage.</param>
            /// <param name="capacityMilliseconds">The longest audio the case can capture.</param>
            public CapturedAudio(IAudioRecorder recorder, int capacityMilliseconds)
            {
                Samples = new float[(long)recorder.SampleRate * recorder.Channels * capacityMilliseconds / 1000];
                _transfer = new float[recorder.SampleRate / 10 * recorder.Channels];
            }

            /// <summary>Gets the interleaved captured samples; only the first <see cref="Count"/> are valid.</summary>
            public float[] Samples { get; }
            /// <summary>Gets the number of valid samples.</summary>
            public int Count { get; private set; }

            /// <summary>Moves every buffered recorder sample into the storage.</summary>
            /// <param name="recorder">The recorder to drain.</param>
            /// <exception cref="Exception">The storage is full.</exception>
            public void Drain(IAudioRecorder recorder)
            {
                int count;
                while ((count = recorder.Read(_transfer)) > 0)
                {
                    Check(Count + count <= Samples.Length, "the captured audio fits the preallocated storage");
                    _transfer.AsSpan(0, count).CopyTo(Samples.AsSpan(Count));
                    Count += count;
                }
            }
        }
    }
